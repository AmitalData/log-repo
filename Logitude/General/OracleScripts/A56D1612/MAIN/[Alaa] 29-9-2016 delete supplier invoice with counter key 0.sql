      ItemPrice,
      NonCustomsItemPrice,
      WholeSaleItemPrice,
      ManufactureIdentifier,
      CustomsBookTypeCode,
      TaxExemptCode,
      OptionalTamaPercentage,
      SalesTaxExemptionTypeCode,
      Tenant,
      ItemPriceCurrencyCode,
      NonCustomsItemPriceCurCode,
      WholeSaleItemPriceCurrencyCode,
      ActualInvoiceLines,
      SequenceNumeric,
      TradeAgreementCode,
      StatisticQuantity,
      InvoiceQuantity,
      AdditionalQuantity,
      InvoiceQuantityType,
      StatisticQuantityType,
      AdditionalQuantityType,
      PreferenceDocumentNumber,
      ItemDescription,
      CertificatesStatusCode,
      IsUsed )  
    (select  DeclarationId,
      1,
      LineNumber,
      ItemCode,
      OriginCountryCode,
      ClassificationCode,
      DangerousClassificationCode,
      DangerousPackingGroupTypeCode,
      ItemPrice,
      NonCustomsItemPrice,
      WholeSaleItemPrice,
      ManufactureIdentifier,
      CustomsBookTypeCode,
      TaxExemptCode,
      OptionalTamaPercentage,
      SalesTaxExemptionTypeCode,
      Tenant,
      ItemPriceCurrencyCode,
      NonCustomsItemPriceCurCode,
      WholeSaleItemPriceCurrencyCode,
      ActualInvoiceLines,
      SequenceNumeric,
      TradeAgreementCode,
      StatisticQuantity,
      InvoiceQuantity,
      AdditionalQuantity,
      InvoiceQuantityType,
      StatisticQuantityType,
      AdditionalQuantityType,
      PreferenceDocumentNumber,
      ItemDescription,
      CertificatesStatusCode,
      IsUsed from  supplierinvoiceitems  where declarationId=c_id and counterkey=0);  
      
      
      insert into SUPPLIERINVIOCEITEMCERTIFICATS (DECLARATIONID,INVOICECOUNTERKEY,LINENUMBER,ITEMCERTIFICATECOUNTERKEY,CERTIFICATENUMBER,TENANT,REQCONFIRMATIONTYPECODE,CERTIFICATEEXEMPTIONTYPECODE,
      ATTACHMENTTYPECODE,RESCONFIRMATIONTYPECODE,CUSTOMSATTACHMENTID,SEQUENCENUMERIC)   ( select DECLARATIONID,1,LINENUMBER,ITEMCERTIFICATECOUNTERKEY,CERTIFICATENUMBER,TENANT,REQCONFIRMATIONTYPECODE,CERTIFICATEEXEMPTIONTYPECODE,
      ATTACHMENTTYPECODE,RESCONFIRMATIONTYPECODE,CUSTOMSATTACHMENTID,SEQUENCENUMERIC from SUPPLIERINVIOCEITEMCERTIFICATS where declarationId =c_id and INVOICECOUNTERKEY =0);
      


 
