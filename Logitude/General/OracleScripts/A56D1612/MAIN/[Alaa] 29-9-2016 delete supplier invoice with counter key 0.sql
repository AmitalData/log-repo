       DEFINEDPERUNITMEASURE, ALTERNATEDEFINEDPERUNITMEASURE, DEFINEDPERUNITQUANTITY, ALTERNATEDEFINEDPERUNITQUANT, MEASUREMENTUNITCODE, ALTERNATEMEASUREMENTUNITCODE, TRADELEVYNUMBER, 
       TOTALBTLCOVERAGENIS, ALTERNATERATE) (select DECLARATIONID, 1, LINENUMBER , TAXTYPECODE, TENANT, TRADEAGREEMENTTYPECODE, TAXRATE, TAXBASEAMOUNT, TAXAMOUNT, DEFEREDTAXAMOUNT,
       DEFINEDPERUNITMEASURE, ALTERNATEDEFINEDPERUNITMEASURE, DEFINEDPERUNITQUANTITY, ALTERNATEDEFINEDPERUNITQUANT, MEASUREMENTUNITCODE, ALTERNATEMEASUREMENTUNITCODE, TRADELEVYNUMBER, 
       TOTALBTLCOVERAGENIS, ALTERNATERATE from SUPPLIERINVOICEITEMSTAXES where declarationid =c_id and INVOICECOUNTERKEY =0);
  
  
   
  
   insert into SUPPLIERINVOICEITEMVEHICLES ( DECLARATIONID, INVOICECOUNTERKEY, INVOICEITEMLINENUMBER, LINENUMBER, SEQUENCENUMERIC, VEHICLETYPECODE, VEHICLECHASSISNUMBER, RICHBITFILENUMBER, 
      VEHICLEID, TENANT ) ( select  DECLARATIONID, 1, INVOICEITEMLINENUMBER, LINENUMBER, SEQUENCENUMERIC, VEHICLETYPECODE, VEHICLECHASSISNUMBER, RICHBITFILENUMBER, 
      VEHICLEID, TENANT from SUPPLIERINVOICEITEMVEHICLES where  declarationid =c_id and INVOICECOUNTERKEY =0);
      
   insert into SUPPLIERINVOICEITEMVEHICLEADDS ( DECLARATIONID, INVOICECOUNTERKEY, INVOICEITEMLINENUMBER, LINENUMBER, VEHICLEMODEL, RICHBITNUMBER, CHASSISNUMBER, ENGINENUMBER, VEHICLEVALUE,
  CHASSISTAX, CHASSISPURCHASETAX, CHASSISVAT, EXEMPT_TYPE, WINDOWNUMBER) (select DECLARATIONID, 1, INVOICEITEMLINENUMBER, LINENUMBER, VEHICLEMODEL, RICHBITNUMBER, CHASSISNUMBER, ENGINENUMBER, VEHICLEVALUE,
  CHASSISTAX, CHASSISPURCHASETAX, CHASSISVAT, EXEMPT_TYPE, WINDOWNUMBER from SUPPLIERINVOICEITEMVEHICLEADDS  where  declarationid =c_id and INVOICECOUNTERKEY =0); 


  
   
    insert into SUPPLIERINVOICEITEMVEHICLEMODS (DECLARATIONID, INVOICECOUNTERKEY, INVOICEITEMLINENUMBER, VEHICLELINENUMBER, LINENUMBER, ADJUSTMENTTYPECODE, DEDUCTAMOUNT, TENANT)
   (select DECLARATIONID, 1, INVOICEITEMLINENUMBER, VEHICLELINENUMBER, LINENUMBER, ADJUSTMENTTYPECODE, DEDUCTAMOUNT, TENANT from SUPPLIERINVOICEITEMVEHICLEMODS 
   where declarationid = c_id and INVOICECOUNTERKEY =0); 
   

    
