using System;
using System.Collections.Generic;
// Note: MSTest Fakes types are generated at build time from .fakes files
#if FAKES_SUPPORTED
using Microsoft.QualityTools.Testing.Fakes;
#endif

namespace Logitude.Test.Infrastructure.Utilities
{
    /// <summary>
    /// MSTest-compatible version of JustMockRegistry.
    /// Lightweight test doubles registry using MSTest fakes instead of JustMock.
    /// </summary>
    public sealed class MSTestFakeRegistry
    {
        private readonly Dictionary<Type, object> _instances = new Dictionary<Type, object>();
#if FAKES_SUPPORTED
        private readonly ShimsContext _shimsContext;
#endif

        public MSTestFakeRegistry()
        {
#if FAKES_SUPPORTED
            _shimsContext = ShimsContext.Create();
#endif
        }

        /// <summary>
        /// Registers an instance in the registry.
        /// </summary>
        public T RegisterInstance<T>(T instance) where T : class
        {
            if (instance == null)
            {
                throw new ArgumentNullException(nameof(instance));
            }

            _instances[typeof(T)] = instance;
            return instance;
        }

        /// <summary>
        /// Creates and registers a fake instance using MSTest fakes.
        /// Note: MSTest fakes require assembly references and .fakes files.
        /// For interfaces, use the Fakes namespace generated by MSTest.
        /// </summary>
        public T RegisterFake<T>() where T : class
        {
            // MSTest fakes are generated at compile time
            // This is a placeholder - actual implementation will depend on the generated Fakes types
            // For now, we'll use a simple approach: create a mock using reflection if possible
            // In practice, tests should create fakes directly using the generated Fakes types
            
            throw new NotImplementedException(
                "MSTest fakes must be created using generated Fakes types. " +
                "Use the Fakes namespace (e.g., new Fakes.ShimIYourInterface()) instead of this method.");
        }

        /// <summary>
        /// Resolves a registered instance.
        /// </summary>
        public T Resolve<T>() where T : class
        {
            if (_instances.TryGetValue(typeof(T), out var instance))
            {
                return (T)instance;
            }

            throw new InvalidOperationException($"Type {typeof(T).FullName} was not registered in MSTestFakeRegistry.");
        }

        /// <summary>
        /// Attempts to resolve a registered instance.
        /// </summary>
        public bool TryResolve<T>(out T instance) where T : class
        {
            if (_instances.TryGetValue(typeof(T), out var stored))
            {
                instance = (T)stored;
                return true;
            }

            instance = null;
            return false;
        }

        /// <summary>
        /// Clears all registered instances.
        /// </summary>
        public void Clear()
        {
            _instances.Clear();
        }

        /// <summary>
        /// Disposes the registry and its shims context.
        /// </summary>
        public void Dispose()
        {
#if FAKES_SUPPORTED
            _shimsContext?.Dispose();
#endif
        }
    }
}

