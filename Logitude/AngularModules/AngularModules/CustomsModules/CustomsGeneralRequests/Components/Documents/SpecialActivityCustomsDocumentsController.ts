    CheckRequestsInProgress(documentsFilingId: string) {
        // Request sheets in progress check
        var authHeader = new Headers();
        var table = window.ObjectTables.filter(d => d.Name === "Customs.Declaration")[0];
        var table2 = window.ObjectTables.filter(d => d.Name === "Customs.CustomsDocument")[0];

        authHeader.append('Token', SessionInfo.Token);
        return defer(() => {
            return ServiceHelper.HttpClient.get(this.apiUrl + '/GetRequestInProgress/?' + 'tenant=' + this.declarationPM.Tenant + '&interfaceTypeCode=2715' + '&objectTableId1=' + table.Id + '&entityId1=' + this.declarationPM.Id + '&objectTableId2=' + table2.Id + '&entityId2=' + encodeURIComponent(documentsFilingId) + '&customFileNo=' + "" + '&displayOnlyMode= false', ServiceHelper.GetHttpHeaders()).pipe(map(response => {
                var serviceResponse: ServiceResponse = new ServiceResponse();
                var requestSheets:any = response;
                if (requestSheets == null || requestSheets.length == 0) {
                    serviceResponse.Result = new DisplayOnlyCheckResult(false, "");
                }
                else {
                    var RequestInProgressInterfaceTypeName = requestSheets[0].InterfaceTypeName;
                    var text = TextCodeTranslator.Translate("Customs.General.RequestInProgress");
                    text = text.replace('{0}', RequestInProgressInterfaceTypeName);
                    serviceResponse.Result = new DisplayOnlyCheckResult(true, text);
                }
                return serviceResponse;
            }),catchError(ServiceHelper.HandleServiceError));
        }

        );
    }

