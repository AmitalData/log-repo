    FillConnectedDocumentPointer(customsDocumentPointerPM: CustomsDocumentPointerPM) {
        if (customsDocumentPointerPM == null) {
            return null;
        }

        let connectedDocumentPointer;

        switch (customsDocumentPointerPM.Child1EntityCode) {
            case EntityCode.SupplierInvoice:
                if (customsDocumentPointerPM.Child3EntityCode === EntityCode.SupplierInvoiceItem) {
                    connectedDocumentPointer = {
                        SelectedIndex: SelectedIndex.SupplierInvoiceItem,
                        DisplayConnectedEntityNumber: customsDocumentPointerPM.Child2EntityId,
                        SupplierInvoiceItemNumber: customsDocumentPointerPM.Child3EntityId,
                    };
                } else {
                    connectedDocumentPointer = {
                        SelectedIndex: SelectedIndex.SupplierInvoice,
                        DisplayConnectedEntityNumber: customsDocumentPointerPM.Child2EntityId,
                    };
                }
                break;

            default:
                connectedDocumentPointer = {
                    SelectedIndex: SelectedIndex.Request,
                };
                break;
        }

        return connectedDocumentPointer;
    }

    private clearOrRemovePointer(
        ticket: CustomsDocumentsTicketPM,
        pointer: CustomsDocumentPointerPM
    ): void {
        if (ticket.CustomsDocumentPointers.length > 1) {
            ticket.RemoveCustomsDocumentPointer(pointer);
        } else {
            pointer.Child2EntityCode = null;
            pointer.Child2EntityId = null;
            pointer.Child3EntityCode = null;
            pointer.Child3EntityId = null;
        }
    }
