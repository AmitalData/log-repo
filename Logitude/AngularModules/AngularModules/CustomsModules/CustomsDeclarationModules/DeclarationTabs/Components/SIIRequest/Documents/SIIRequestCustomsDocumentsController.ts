    SelectionInvoicesCompleted(args, customsDocumentsTicket: CustomsDocumentsTicketPM,) {
        if (args.SelectedInvoices != null) {
            customsDocumentsTicket.ConnectedInvoicesSequences = args.ConnectedInvoices;
            customsDocumentsTicket.ConnectedInvoiceItemsSequences = args.ConnectedInvoiceItems;
            var pointers: CustomsDocumentPointerPM[] = [];
            customsDocumentsTicket.CustomsDocumentPointers.forEach((pointer) => {
                pointers.push(pointer);
            });
            pointers.forEach((pointer) => {
                if (pointer.Child2EntityId != null) {
                    var exists = args.SelectedInvoices.Collection.filter(d => d.InvoiceCounterKey + "" == pointer.Child2EntityId)[0];
                    if (!exists) {
                        var editedPointer: CustomsDocumentPointerPM = customsDocumentsTicket.CustomsDocumentPointers.filter(d => d.Id == pointer.Id)[0];
                        if (editedPointer != null) {
                            if (customsDocumentsTicket.CustomsDocumentPointers.length > 1) {
                                customsDocumentsTicket.RemoveCustomsDocumentPointer(editedPointer);
                            }
                            else {

                                editedPointer.Child2EntityCode = null;
                                editedPointer.Child2EntityId = null;
                                editedPointer.Child3EntityCode = null;
                                editedPointer.Child3EntityId = null;

                            }
                        }
                    }
                }
                if (pointer.Child3EntityId != null) {
                    var exists = args.StaticSelectedInvoiceItems.Collection.filter(d => d.CounterKey + "" == pointer.Child2EntityId && d.LineNumber + "" == pointer.Child3EntityId)[0];
                    if (!exists) {
                        var editedPointer: CustomsDocumentPointerPM = customsDocumentsTicket.CustomsDocumentPointers.filter(d => d.Id == pointer.Id)[0];
                        if (editedPointer != null) {
                            if (customsDocumentsTicket.CustomsDocumentPointers.length > 1) {
                                customsDocumentsTicket.RemoveCustomsDocumentPointer(editedPointer);
                            }
                            else {
                                editedPointer.Child2EntityCode = null;
                                editedPointer.Child2EntityId = null;
                                editedPointer.Child3EntityCode = null;
                                editedPointer.Child3EntityId = null;
                            }
                        }
                    }
                }
            });

            args.SelectedInvoices.Collection.forEach((invoice) => {
                var hasLineschosen = args.StaticSelectedInvoiceItems.Collection.filter(d => d.DeclarationId == invoice.DeclarationId && d.CounterKey == invoice.InvoiceCounterKey)[0];
                if (!hasLineschosen) {
                    var exists = customsDocumentsTicket.CustomsDocumentPointers.filter(d => d.Child2EntityId == invoice.InvoiceCounterKey + "")[0];
                    if (!exists) {
                        var declarationPointer: CustomsDocumentPointerPM = customsDocumentsTicket.CustomsDocumentPointers.filter(d => d.ParentEntityId == invoice.DeclarationId && d.Child1EntityId == this.childEntity1Code && d.Child2EntityId == null && d.Child3EntityId == null)[0];
                        if (declarationPointer == null) {
                            var newPointer: CustomsDocumentPointerPM = new CustomsDocumentPointerPM(customsDocumentsTicket)

                            newPointer.Tenant = SessionLocator.Tenant;
                            newPointer.ParentEntityId = this.declarationPM.Id;
                            newPointer.ParentEntityCode = "Declaration";//"Declaration",
                            newPointer.Child1EntityCode = "SIIRequest";
                            newPointer.Child2EntityCode = "SupplierInvoice";
                            newPointer.Child3EntityCode = null;
                            newPointer.Child1EntityId = this.childEntity1Id;
                            newPointer.Child2EntityId = invoice.InvoiceCounterKey + "";
                            newPointer.Child3EntityId = null;
                            customsDocumentsTicket.AddCustomsDocumentPointer(newPointer);

                        }
                        else {
                            declarationPointer.Child2EntityId = invoice.InvoiceCounterKey + "";
                            declarationPointer.Child2EntityCode = "SupplierInvoice";
                        }
                    }
                }
                else {
                    var existedPtr: CustomsDocumentPointerPM = customsDocumentsTicket.CustomsDocumentPointers.filter(d => d.Child2EntityId == invoice.InvoiceCounterKey + "" && d.Child3EntityId == null)[0];
                    if (existedPtr != null) {
                        customsDocumentsTicket.RemoveCustomsDocumentPointer(existedPtr);
                    }
                }
            });
        }

        if (args.StaticSelectedInvoiceItems != null) {
            args.StaticSelectedInvoiceItems.Collection.forEach((invoiceItem) => {
                var exists = customsDocumentsTicket.CustomsDocumentPointers.filter(d => d.Child2EntityId == invoiceItem.CounterKey + "" && d.Child3EntityId == invoiceItem.LineNumber + "")[0];
                if (!exists) {
                    var declarationPointer: CustomsDocumentPointerPM = customsDocumentsTicket.CustomsDocumentPointers.filter(d => d.ParentEntityId == invoiceItem.DeclarationId
                        && d.Child2EntityId == null && d.Child3EntityId == null)[0];
                    if (declarationPointer != null) {
                        declarationPointer.Child2EntityId = invoiceItem.CounterKey + "";
                        declarationPointer.Child2EntityCode = "SupplierInvoice";
                        declarationPointer.Child3EntityId = invoiceItem.LineNumber + "";
                        declarationPointer.Child3EntityCode = "SupplierInvoiceItem";
                    }
                    else {
                        var newPointer: CustomsDocumentPointerPM = new CustomsDocumentPointerPM(customsDocumentsTicket)
                        {
                            newPointer.Tenant = SessionLocator.Tenant;
                            newPointer.ParentEntityId = this.declarationPM.Id;
                            newPointer.ParentEntityCode = "Declaration";
                            newPointer.Child1EntityCode = "SIIRequest";
                            newPointer.Child2EntityCode = "SupplierInvoice";
                            newPointer.Child3EntityCode = "SupplierInvoiceItem";
                            newPointer.Child1EntityId = this.childEntity1Id;
                            newPointer.Child2EntityId = invoiceItem.CounterKey + "";
                            newPointer.Child3EntityId = invoiceItem.LineNumber + "";
                        };
                        customsDocumentsTicket.AddCustomsDocumentPointer(newPointer);
                    }
                }

            });
        }

        this.SelectionCompleted.emit(args);
    }

