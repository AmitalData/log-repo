#!/usr/bin/env node
/**
 * Updates package.json version with timestamp format: mmHHddMMyyyy
 * Format: minute, hour, day, month, year
 */

const fs = require('fs');
const path = require('path');

function resolveRepoRoot(startDir) {
    let dir = startDir;
    while (dir && dir !== path.dirname(dir)) {
        if (fs.existsSync(path.join(dir, 'package.json'))) return dir;
        dir = path.dirname(dir);
    }
    return startDir;
}

const repoRoot = resolveRepoRoot(process.cwd());
const packageJsonPath = path.join(repoRoot, 'package.json');
const versionTsPath = path.join(repoRoot, 'src', 'version.ts');

if (!fs.existsSync(packageJsonPath)) {
    console.error('Error: package.json not found');
    process.exit(1);
}

try {
    // Read package.json
    const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
    
    // Generate version: mmHHddMMyyyy (minute, hour, day, month, year)
    const now = new Date();
    const minute = String(now.getMinutes()).padStart(2, '0');
    const hour = String(now.getHours()).padStart(2, '0');
    const day = String(now.getDate()).padStart(2, '0');
    const month = String(now.getMonth() + 1).padStart(2, '0');
    const year = String(now.getFullYear());
    
    const newVersion = `${minute}${hour}${day}${month}${year}`;
    
    // Update version in package.json
    const oldVersion = packageJson.version;
    packageJson.version = newVersion;
    
    // Write back to package.json with proper formatting
    fs.writeFileSync(packageJsonPath, JSON.stringify(packageJson, null, 4) + '\n', 'utf8');
    
    // Update version.ts file
    const versionTsContent = `// This file is auto-generated by tools/update-version.js
// Do not edit manually
export const APP_VERSION = '${newVersion}';
`;
    fs.writeFileSync(versionTsPath, versionTsContent, 'utf8');
    
    console.log(`Version updated: ${oldVersion} -> ${newVersion}`);
} catch (error) {
    console.error('Error updating version:', error.message);
    process.exit(1);
}
