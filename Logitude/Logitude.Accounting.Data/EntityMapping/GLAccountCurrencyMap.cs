namespace Logitude.Accounting.Data.EntityMapping
{
 
    public class GLAccountCurrencyMap : EntityTypeConfiguration<GLAccountCurrency>
    {
	    string dbms;
        public GLAccountCurrencyMap()
        { 
				this.ToTable("GLAccountCurrencies");
		
		    this.HasKey(t => new { t.Id });
	 
            this.Property(t => t.Id).HasColumnName("Id").IsRequired().HasMaxLength(15).IsUnicode(false);

            this.Property(t => t.Tenant).HasColumnName("Tenant").IsRequired();

            this.Property(t => t.GLAccountId).HasColumnName("GLAccountId").IsRequired().HasMaxLength(15).IsUnicode(false);

            this.Property(t => t.CurrencyId).HasColumnName("CurrencyId").IsRequired().HasMaxLength(15).IsUnicode(false);

            this.Property(t => t.MainGLAccountId).HasColumnName("MainGLAccountId").IsRequired().HasMaxLength(15).IsUnicode(false);
        }
    }
