            string SISequenceNumeric)

        {
            var myLOGISUPPACC = new LOGISUPPACC();
            myLOGISUPPACC.LogitudeSupplierAccount = new LogitudeSupplierAccount[] { new LogitudeSupplierAccount() };
            myLOGISUPPACC.LogitudeSupplierAccount[0].Document = selectedSupplierInvoiceItemPM.PreferenceDocumentNumber;
            myLOGISUPPACC.LogitudeSupplierAccount[0].ItemNo = selectedSupplierInvoiceItemPM.ItemCode;
            myLOGISUPPACC.LogitudeSupplierAccount[0].OriginCcountryId = selectedSupplierInvoiceItemPM.OriginCountryCode;
