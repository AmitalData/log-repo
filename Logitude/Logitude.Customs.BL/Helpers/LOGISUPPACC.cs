            if (selectedSupplierInvoiceItemPM.InvoiceQuantity.HasValue) myLOGISUPPACC.LogitudeSupplierAccount[0].Quantity = selectedSupplierInvoiceItemPM.InvoiceQuantity.ToString();
            if (selectedSupplierInvoiceItemPM.StatisticQuantity.HasValue) myLOGISUPPACC.LogitudeSupplierAccount[0].StatisticQuantity = selectedSupplierInvoiceItemPM.StatisticQuantity.ToString();
            myLOGISUPPACC.LogitudeSupplierAccount[0].RateGroup = selectedSupplierInvoiceItemPM.TradeAgreementCode;
            myLOGISUPPACC.LogitudeSupplierAccount[0].SupplierAccountLine = SISequenceNumeric;//selectedSupplierInvoiceItemPM.SequenceNumeric.ToString();
            myLOGISUPPACC.LogitudeSupplierAccount[0].SupplierItemLine = selectedSupplierInvoiceItemPM.LineNumber.ToString();
            myLOGISUPPACC.LogitudeSupplierAccount[0].Unit = selectedSupplierInvoiceItemPM.InvoiceQuantityType;
            myLOGISUPPACC.LogitudeSupplierAccount[0].StatisticQuantityUnit = selectedSupplierInvoiceItemPM.StatisticQuantityType;

            var l = new List<RequiredCertificates>();
            int lineNum = 0;
            foreach (var item in supplierInvioceItemCertificatPMList)
            {
                lineNum++;
                var curr = new RequiredCertificates();
                curr.AttachmentType = item.AttachmentTypeCode;
                curr.CertificateExemptionType = item.CertificateExemptionTypeCode;
                curr.CertificateNumber = item.CertificateNumber;
                curr.CustomsAttachmentId = item.CustomsAttachmentID;
                curr.LineNo = lineNum.ToString();
                curr.RequestConfirmationType = item.ReqConfirmationTypeCode;
                curr.ResponseConfirmationType = item.ResConfirmationTypeCode;
                curr.SupplierAccount = item.InvoiceCounterKey.ToString();
                curr.SupplierItem = item.LineNumber.ToString();

                l.Add(curr);
            }
            myLOGISUPPACC.LogitudeSupplierAccount[0].RequiredCertificates = l.ToArray();
            return myLOGISUPPACC;
        }


