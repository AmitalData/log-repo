            //syncStatusRep.SubmitChanges();

            //get ExternalCodesLastUpdate from AccountingSystemsSyncStatus
            //get single AccountingSystemsSettings according to tenant and calculate (requestDate-ExternalCodesLastUpdate)=requestInterval
            DateTime? requestDate = TenantServerConfigration.GetCurrentDateTime(tenant);
            AccountingSystemsSettingRepository accountingSystemsSettingRep = new AccountingSystemsSettingRepository(tenant);
            AccountingSystemsSetting accountingSystemsSetting = accountingSystemsSettingRep.GetSingleAccountingSystemsSetting(tenant);
            if (accountingSystemsSetting == null)
            {
                accountingSystemsSetting = new AccountingSystemsSetting()
                {
                    GetExternalCodeInterval = 30,
                    Id = IdCounter.GetNumber("AccountingSystemsSetting", tenant).ToString(),
                    Tenant = tenant,
                };
                accountingSystemsSettingRep.Add(accountingSystemsSetting);
                accountingSystemsSettingRep.SubmitChanges();
            }

            int requestInterval = 0;
            if (status.ExternalCodesLastUpdate != null)
            {
                requestInterval = (int)(requestDate.Value - status.ExternalCodesLastUpdate.Value).TotalMinutes;
            }
            else
            {
               status.ExternalCodesLastUpdate = requestDate.Value.AddMinutes(-30);
                requestInterval = (int)(requestDate.Value - status.ExternalCodesLastUpdate.Value).TotalMinutes;
            }

            //if(requestInterval >= GetExternalCodeInterval) begin update tables
            //check interval first

            //Get Ticket get extTablesRequestCount if >0 call GetNextExternalTableRequest(extTablesRequestCount)
            if (accountingSystemsSetting.UpdateOnNextRequest)
            {
                ticketPM.ExternalTablesRequestCount = 5;
                accountingSystemsSetting.UpdateOnNextRequest = false;
                accountingSystemsSettingRep.Update(accountingSystemsSetting);
                accountingSystemsSettingRep.SubmitChanges();
            }
            else if (requestInterval >= accountingSystemsSetting.GetExternalCodeInterval && ticketPM.ExternalTablesRequestCount == 0)
            {
                //requests for external tables.
                ticketPM.ExternalTablesRequestCount = 5;
            }

            if (ticketPM.RequestCount == 0)
            {
                ticketPM.RequestCount = GetReadyInvoicesCount(tenant);
            }

            if (ticketPM.ExternalTablesRequestCount > 0)
            {
               
                request = GetNextExternalTableRequest(ticketPM.ExternalTablesRequestCount, status.ExternalCodesLastUpdate);
                
                ticketPM.ExternalTablesRequestCount = ticketPM.ExternalTablesRequestCount - 1;
                if (ticketPM.ExternalTablesRequestCount == 0)
                {
                    DateTime updateDate = TenantServerConfigration.GetCurrentDateTime(tenant);
                    //after updating tables update ExternalCodesLastUpdate to the updateDate
                   
                    status.ExternalCodesLastUpdate = updateDate;
                    syncStatusRep.Update(status);
                    syncStatusRep.SubmitChanges();

            }
            }
            else
            {
                if (ticketPM.RequestCount > 0)
                {
                    request = TransferNextReadyInvoice(ticketPM);
                    ticketPM.RequestCount = ticketPM.RequestCount - 1;
                    if (request == null && ticketPM.RequestCount != 0)
                    {
                        request = TransferNextReadyInvoice(ticketPM);
                        ticketPM.RequestCount = ticketPM.RequestCount - 1;
                    }
                }

            }
            IInvoiceContext context = InvoiceContext.GetContext(0);
            QuickbooksSyncRequestTicketService service = new QuickbooksSyncRequestTicketService(context);
            service.Update(ticketPM);

            if (string.IsNullOrEmpty(request))
            {
                request = GetCheckRequest();
            }

            return request;
        }

        private string GetCheckRequest()
        {
            //paymentterms = terms
            XmlDocument inputXMLDoc = new XmlDocument();
            inputXMLDoc.AppendChild(inputXMLDoc.CreateXmlDeclaration("1.0", null, null));
            inputXMLDoc.AppendChild(inputXMLDoc.CreateProcessingInstruction("qbxml", "version=\"4.0\""));

            XmlElement qbXML = inputXMLDoc.CreateElement("QBXML");
            inputXMLDoc.AppendChild(qbXML);
            XmlElement qbXMLMsgsRq = inputXMLDoc.CreateElement("QBXMLMsgsRq");
            qbXML.AppendChild(qbXMLMsgsRq);
            qbXMLMsgsRq.SetAttribute("onError", "stopOnError");
            XmlElement customerQueryRq = inputXMLDoc.CreateElement("TermsQueryRq");
            qbXMLMsgsRq.AppendChild(customerQueryRq);
            customerQueryRq.SetAttribute("requestID", "33");
            XmlElement maxReturned = inputXMLDoc.CreateElement("MaxReturned");
            customerQueryRq.AppendChild(maxReturned).InnerText = "1";
        
            string strRequestXML = inputXMLDoc.OuterXml;
            return strRequestXML;
        }

        private string  GetNextExternalTableRequest(int extTablesRequestCount,DateTime? dateModified)
        {
            switch (extTablesRequestCount)
            {
                case 5: { return GetSalesTaxCode(dateModified); }
                case 4: { return GetCustomers(dateModified); }
                case 3: { return GetItemSalesTaxes(dateModified); }
                case 2: { return GetTerms(dateModified); }
                case 1: { return GetItems(dateModified); }

                default: { return GetCustomers(dateModified); }
            }
        }


		
