        private void AnalyzeInvoiceXml(string response, string ticket)
        {
            //if xml is not normal i.e invoice has error (has no <invoiceret>)
            //getsingle invoice by number and update status to error in transfer and transfer error = statusmessage from xml
            //else if normal get single and update status to transfered and transfer error =null
            QuickbooksSyncRequestTicketPM ticketPM = GetCurrentTicketPM(ticket);
            int tenant=ticketPM.Tenant;
            XmlDocument doc = new XmlDocument();
            doc.LoadXml(response);
            string responseType = doc.DocumentElement.FirstChild.FirstChild.Name;
            ARInvoiceQuery query = new ARInvoiceQuery(tenant);
            ARInvoicePM invoice = query.GetSingleInvoiceByInvoiceNumber(ticketPM.ReferenceNumber, tenant);
            if (responseType == "InvoiceQueryRs" || responseType == "CreditMemoQueryRs")
            {

                var invoiceRet = doc.DocumentElement.FirstChild.FirstChild.FirstChild;
                if (invoiceRet != null)
                {
                    // normal xml invoice found
                    // normal returned tag<invoiceret> i.e exists in qb update status to transfered 
                    invoice.TransferError = null;
                    invoice.TransferStatusCode = "TR";
                    invoice.IsTransferStarted = false;
                    invoice.IsTransferStatusSetManually = true;
                }
                else
                {
                    //invoice not found xml
                    invoice.TransferError = null;
                    invoice.TransferStatusCode = "RD";
                    invoice.IsTransferStarted = false;
                    invoice.IsTransferStatusSetManually = true;
                    
                }
                //if xml is not normal i.e invoice doesn't exist in qb
                //getsingle invoice by number and update status to ready for transfer and isTransferstarted =false
                
                ticketPM.IsCurrentInvoiceChecked = true;

            }
            else if (responseType == "InvoiceAddRs" || responseType == "CreditMemoAddRs")
            {
                var invoiceRet = doc.DocumentElement.FirstChild.FirstChild.FirstChild;
                if (invoiceRet != null)
                {
                    // normal xml
                    invoice.TransferError = null;
                    invoice.TransferStatusCode = "TR";
                    invoice.IsTransferStarted = false;
                    invoice.IsTransferStatusSetManually = true;
                }
                else
                {
                    // error xml
                    invoice.TransferError = doc.DocumentElement.FirstChild.FirstChild.Attributes["statusMessage"].Value.ToString();
                    invoice.TransferStatusCode = "ET";
                    invoice.IsTransferStarted = true;
                    invoice.IsTransferStatusSetManually = true;
                }
                ticketPM.IsCurrentInvoiceChecked = false;
            }

            IInvoiceContext context = InvoiceContext.GetContext(0);
            QuickbooksSyncRequestTicketService service = new QuickbooksSyncRequestTicketService(context);
            service.Update(ticketPM);

            IInvoiceContext invoiceContext = InvoiceContext.GetContext(tenant);
            string systemEmail = "system@tenant" + tenant + ".com";
            ARInvoiceService invoiceService = new ARInvoiceService(context, tenant, systemEmail);
            invoiceService.SetChangeSet(invoice.InvoiceLines, invoice.InvoicePayments,invoice.ConstituentInvoices);
            invoiceService.Update(invoice);
        }

        private void UpdateExternalTables(string response,string ticket)
        {

            //get xml responses analyze them
            //get external tables by tenant
            //foreach response check if listID exists in the table if not add new record if exists update the name of the existed record
            QuickbooksSyncRequestTicketPM ticketPM = GetCurrentTicketPM(ticket);
            XmlDocument doc = new XmlDocument();
            int tenant = ticketPM.Tenant;

            ExternalSystemsTablesCodeRepository externalRep = new ExternalSystemsTablesCodeRepository(tenant);
            List<ExternalSystemsTablesCode> externalTables = externalRep.GetExternalSystemsTablesCodes(tenant).ToList();


            string query = null;

            doc.LoadXml(response);
      
            string responseName = doc.DocumentElement.FirstChild.FirstChild.Name;
            string logitudeTableName = null;
            switch (responseName)
            {
                case "ItemSalesTaxQueryRs": { logitudeTableName = "VatType"; break; }
                case "ItemQueryRs": { logitudeTableName = "ChargesType"; break; }
                case "TermsQueryRs": { logitudeTableName = "PaymentTerm"; break; }
                case "CustomerQueryRs": { logitudeTableName = "Card"; break; }
                case "SalesTaxCodeQueryRs": { logitudeTableName = "TaxCode"; break; }
                default: { break; }
            }
            if (!string.IsNullOrEmpty(logitudeTableName))
            {
                if (doc.DocumentElement.FirstChild.FirstChild.FirstChild != null)
                {
                query = doc.DocumentElement.FirstChild.FirstChild.FirstChild.Name;
                
                if (!string.IsNullOrEmpty(query))
                {

                    XmlNodeList nodes = doc.DocumentElement.FirstChild.FirstChild.ChildNodes;//doc.GetElementsByTagName(query);

                    foreach (XmlNode node in nodes)
                    {
                        XmlNode listID = node.SelectSingleNode("ListID");
                        string ListId = listID.InnerText;

                        XmlNode name = node.SelectSingleNode("Name");

                        ExternalSystemsTablesCode table = (from a in externalTables
                                                           where a.Code == ListId
                                                           select a).FirstOrDefault();

                        if (table != null)
                        {

                            if (name != null)
                                table.Name = (name.InnerText.Length > 60 ? name.InnerText.Substring(0, 59) : name.InnerText);

                        }
                        else
                        {
                            ExternalSystemsTablesCode external = new ExternalSystemsTablesCode()
                            {
                                Id = IdCounter.GetNumber("ExternalSystemsTablesCode", tenant),
                                Code = ListId,
                                Name = name != null ? (name.InnerText.Length>60? name.InnerText.Substring(0,59):name.InnerText) : null,
                                Tenant = tenant,
                                LogitudeTable = logitudeTableName,
                                CreatedDate = TenantServerConfigration.GetCurrentDateTime(tenant),
                                SearchFields = ListId + ',' + name.InnerText + ',' + logitudeTableName,
                                UpdatedDate = TenantServerConfigration.GetCurrentDateTime(tenant),
                            };
                            
                            externalRep.Add(external);
                            externalRep.SubmitChanges();
                        }
                    }

               
                    }
                }
                else
                {
                    AccountingSystemsSyncStatusRepository statusRep = new AccountingSystemsSyncStatusRepository(tenant);
                    AccountingSystemsSyncStatus status = statusRep.GetSingleAccountingSystemsSyncStatus(tenant);
                    status.LastError = doc.DocumentElement.FirstChild.FirstChild.Attributes["statusMessage"].Value.ToString();
                    status.LastErrorDate = TenantServerConfigration.GetCurrentDateTime(tenant);
                    statusRep.Update(status);
                    statusRep.SubmitChanges();
                }
            }





