        private string GetNextRequest(string ticket)
        {
            string request = "";

            QuickbooksSyncRequestTicketPM ticketPM = GetCurrentTicketPM(ticket);
            int tenant = ticketPM.Tenant;
            
      
            //get single AccountingSystemsSyncStatus  according to tenant
            AccountingSystemsSyncStatusRepository syncStatusRep = new AccountingSystemsSyncStatusRepository(tenant);
            AccountingSystemsSyncStatus status = syncStatusRep.GetSingleAccountingSystemsSyncStatus(tenant);

