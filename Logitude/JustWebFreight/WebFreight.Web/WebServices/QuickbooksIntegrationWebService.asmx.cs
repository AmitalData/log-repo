        private double getDueInDays(string term)
        {
            double dueInDays = 0;
            switch (term)
            {
                case "Due on receipt":
                    dueInDays = 0;
                    break;
                case "Net 15":
                    dueInDays = 15;
                    break;
                case "Net 30":
                    dueInDays = 30;
                    break;
                case "Net 60":
                    dueInDays = 60;
                    break;
                default:
                    dueInDays = 0;
                    break;
            }
            return dueInDays;
        }

