namespace WebFreight.Web.Controllers.CustomsModel.Extended
{
    public class InterfaceManagementPMExtendController : ApiController
    {


        public HttpResponseMessage GetSingleInterfaceManagementwithDefinition(string code, int tenant)
        {
            try
            {
                string token = HttpContext.Current.Request.Headers["Token"];
                AuthenticationToken authToken = AuthenticationTokenRepository.GetSingleTokenFromCache(token);
                //int tenant = authToken.Tenant;
                string loggedUserEmail = authToken.Email;
                SecurityUtility.AuthenticationOnTenant(tenant);

                ICustomContext customContext = CustomContext.GetContext(authToken.Tenant);

                var qs = new InterfaceManagementQueryService(customContext);
                var pm = qs.GetSingleInterfaceManagementwithDefinition(code, tenant);

                return Request.CreateResponse(HttpStatusCode.OK, pm);
            }

            catch (Exception ex)
            {
                return Request.CreateResponse(HttpStatusCode.BadRequest, ApiExceptionBuilder.BuildException(ex));
            }
        }

        public HttpResponseMessage PutInterfaceManagementPM(InterfaceManagementPM entityPM)
        {
            if (ModelState.IsValid)
            {
                try
                {
                    using (TransactionScope scope = TransactionFactory.GetTransaction())
                    {
                        string token = HttpContext.Current.Request.Headers["Token"];
                        AuthenticationToken authToken = AuthenticationTokenRepository.GetSingleTokenFromCache(token);
                        SecurityUtility.AuthenticationOnTenant(authToken.Tenant);
                        ///SecurityUtility.CheckContactFeature("Customs.InterfaceManagement", "UPDATE", authToken.Tenant);

                        ICustomContext MyContext = CustomContext.GetContext(authToken.Tenant);
                        var service = new InterfaceManagementUpdateService(MyContext, new Dictionary<string, IContext>(), authToken.Tenant);
                        
                        entityPM.ChangeSetOp = Simplog.Server.Infrastructure.ChangeSetOperation.Update;
                        service.Update(entityPM, true);

                        
                        scope.Complete();
                        return Request.CreateResponse(HttpStatusCode.OK, entityPM);
                    }
                }

                catch (Exception ex)
                {
                    return Request.CreateResponse(HttpStatusCode.BadRequest, ApiExceptionBuilder.BuildException(ex));
                }
            }
            else
            {
                return Request.CreateResponse(HttpStatusCode.BadRequest, ApiExceptionBuilder.BuildModelException(ModelState));
            }
        }
    }
